const assert=require('assert/strict');
const {JSDOM,VirtualConsole}=require('jsdom');
const {assets,comparisonPayload,installMsentityViewer,handleAction}=require('../src/features/training-metrics/msentity-viewer');
(async()=>{
  const source=assets();assert.match(source.js,/function receiveComparison/);
  const root=new JSDOM('<div id="mount"></div>',{runScripts:'outside-only'});
  const {window}=root;let state={metricsSelected:['loss']},actions=[],child=null,queue=[];
  const api={getState:()=>state,setState:value=>{state=value;},postMessage:message=>actions.push(message)};
  window.adapterAssets=source;window.adapterApi=api;
  window.eval('window.viewer=('+installMsentityViewer.toString()+')(window.adapterAssets,window.adapterApi)');
  const record={smiles:'CCO',assignment_score:.8,assignment_score_without_precursor:.6,cosine_similarity:.7,cosine_similarity_without_precursor:.5,main_adduct:'[M+H]+',
    generated_peaks:[{mz:47,intensity:1,precursor:true},{mz:20,intensity:.4}],original_peaks:[{mz:47,intensity:.8,precursor:true},{mz:20,intensity:1}]};
  const payload=comparisonPayload(record,'epoch_1:0');
  assert.deepEqual(payload.top.spectrum.mz,[47,20]);assert.equal(payload.bottom.row.SMILES,'CCO');
  assert.equal(payload.top.row['Saved cosine (without precursor)'],.5);
  const mount=window.document.getElementById('mount');window.viewer.update(mount,payload);
  const frame=mount.querySelector('iframe');assert.ok(frame);assert.equal(frame.style.height,'540px');assert.equal(frame.getAttribute('scrolling'),'no');
  assert.match(frame.srcdoc,/grid-template-columns:minmax\(0,1fr\) minmax\(0,40%\)/);
  assert.match(frame.srcdoc,/peak-scroll\{max-height:none;overflow:visible\}/);
  assert.ok(frame.srcdoc.includes(source.js),'the unmodified libs spectrum.js must be embedded');
  frame.contentWindow.postMessage=message=>{if(child)child.window.dispatchEvent(new child.window.MessageEvent('message',{data:message}));else queue.push(message);};
  const errors=[];const console=new VirtualConsole();console.on('jsdomError',error=>errors.push(error));
  child=new JSDOM(frame.srcdoc,{runScripts:'dangerously',virtualConsole:console,beforeParse(w){
    w.requestAnimationFrame=callback=>w.setTimeout(callback,0);
    Object.defineProperty(w,'parent',{value:{postMessage:message=>window.dispatchEvent(new window.MessageEvent('message',{source:frame.contentWindow,data:message}))}});
  }});
  for(const message of queue)child.window.dispatchEvent(new child.window.MessageEvent('message',{data:message}));queue=[];
  assert.deepEqual(errors.map(e=>e.message),[]);
  assert.ok(child.window.document.getElementById('spectrum-svg'),'the real msentity renderer must draw the mirror plot');
  assert.match(child.window.document.body.textContent,/Upper.*Generated/s);
  assert.match(child.window.document.body.textContent,/Lower.*Observed/s);
  assert.match(child.window.document.body.textContent,/Saved cosine \(with precursor\)/);
  assert.match(child.window.document.body.textContent,/CCO/);
  const rendered=child.window.document.getElementById('spectrum-svg');
  window.viewer.update(mount,comparisonPayload(record,'epoch_1:0'));
  assert.strictEqual(child.window.document.getElementById('spectrum-svg'),rendered,'unchanged selection must preserve native zoom and controls');
  window.viewer.update(mount,comparisonPayload({...record,smiles:'CCCO'},'epoch_2:0'));
  assert.strictEqual(mount.querySelector('iframe'),frame,'epoch changes must preserve iframe identity');
  assert.match(child.window.document.body.textContent,/CCCO/);
  window.dispatchEvent(new window.MessageEvent('message',{source:frame.contentWindow,data:{type:'fredisValidationSpectrum',message:{type:'viewer-state',value:{exportSettings:{width:1000}}}}}));
  assert.deepEqual(state.metricsSelected,['loss']);assert.equal(state.validationViewerState.exportSettings.width,1000);
  window.dispatchEvent(new window.MessageEvent('message',{source:frame.contentWindow,data:{type:'fredisValidationSpectrum',message:{type:'viewer-height',height:920}}}));
  assert.equal(frame.style.height,'920px','the iframe must fit the complete peak table without internal scrolling');
  const saved=[];const vscode={Uri:{file:fsPath=>({fsPath})},window:{showSaveDialog:async options=>options.defaultUri},workspace:{fs:{writeFile:async(uri,bytes)=>saved.push({uri,bytes})}}};
  await handleAction(vscode,{type:'save-peaks',basename:'validation',contents:{tsv:'mz\tintensity\n20\t1\n'}});
  assert.equal(Buffer.from(saved[0].bytes).toString(),'mz\tintensity\n20\t1\n');
  child.window.close();root.window.close();
  process.stdout.write('Validation msentity: real libs renderer, paired spectra, metadata, stable iframe, viewer state and export passed.\n');
})().catch(error=>{process.stderr.write(error.stack+'\n');process.exitCode=1;});
